// edit-contract.ts —— **改稿契约**（R25）
//
// 用户判词："要求用户在使用过程中修改某些地方也完全可以，而不是只有第一遍直出才有高质量"。
//
// 旧实现只有一句"开始撰写正文"，**改稿回合与初稿回合拿到的是同一条指令**——于是模型很容易
// 顺手把整篇重写一遍：用户只想改一段，结果别的段落、气泡骨架、素材引用、篇幅全跟着变了
// （"改一处 → 全文降级"）。这里补一条**只在"本回合开始时确实存在一份已验收文稿"时**给出的改稿契约。
//
// 边界（铁律 6）：**这不是对话路由，也不是前端状态机**——消息照旧直通模型；这里只把
// "上面那份文稿是既成品、改稿要收着改"这个**事实**告诉它，**改不改、改哪儿仍由模型自己判断**。
// 措辞刻意写成条件式（"若用户是在要求修改…若是在要求重做…"），不替模型分流。
//
// 为什么单独立一个模块：本文件**不依赖 Vite**（只引用 persona 的一句短引用），
// 于是离线回归 `scripts/edit-contract-check.mjs` 能直接 import 它做断言；
// 放进 `prep.ts` 会连带 `retrieval.ts` 的 `import.meta.glob`，在纯 Node 下起不来。
import { MATERIAL_GROUNDING_REF } from './persona.ts'

export function writeInstruction(hasPriorDoc: boolean): string {
  const base =
    '开始撰写正文：正文放进一个 ```v2 围栏代码块（不要 ```html）。正文前可以用普通文字自然说明（写好了/按什么风格/采纳什么默认）。'
  const edit = hasPriorDoc
    ? '\n**这一轮是"改稿"**（上面已给出当前正式文稿）：若用户是在要求**修改某个地方**（改文字 / 换说法 / 调某一段 / 加删一节），' +
      '**只改他指出的那处**，其余**逐字保留**——段落顺序、组件、气泡骨架（`[[boxes:…]]` 声明）、素材引用、篇幅都不要动；' +
      '**仍要输出完整正文**（一个 ```v2 围栏，未改动的部分原样复制，不要只给改动片段、也不要省略成"同上"）。' +
      '不要顺手润色没被点到的段落、不要重排、不要新增他没要求的内容。\n' +
      '若用户是在要求**重做 / 换方向**（"重新写一篇""换个主题""整篇重来"），按新写处理。'
    : ''
  return base + edit + MATERIAL_GROUNDING_REF + '知识摘要仍适用。'
}

/** 兼容旧调用（等价于"新写一篇"）。新代码请直接用 `writeInstruction(hasPriorDoc)`。 */
export const WRITE_INSTRUCTION = writeInstruction(false)
